#include "stick_installer.h"

#include "text.h"

const char STICK_INSTALLER_NAME[] = "install.sh";

static const char TEMPLATE[] =
    "#!/bin/sh\n"
    "# Written by imprint bundle: installs the setup '%s' from this stick. As root on the stick's live system:\n"
    "#   mount -o ro,loop /dev/disk/by-label/Ventoy /srv && sh /srv/imprint/install.sh\n"
    "# Arguments are passed on to imprint-engine install (--disk, --data-disk, --personal).\n"
    "set -eu\n"
    "setup=%s\n"
    "view=imprint-stick\n"
    "stick=${IMPRINT_STICK_MOUNT:-/run/imprint-stick}\n"
    "running_from=$(cd \"$(dirname \"$0\")\" && pwd -P)\n"
    "\n"
    "say() {\n"
    "    echo \"imprint: $*\" >&2\n"
    "}\n"
    "\n"
    "fail() {\n"
    "    say \"$*\"\n"
    "    exit 3\n"
    "}\n"
    "\n"
    "# Ventoy holds its partition while it serves the booted ISO: a mount of it is refused, a second read-only\n"
    "# mapping is not, and through the mapping the engine still sees which disk is the stick.\n"
    "attach_stick() {\n"
    "    if mountpoint -q \"$stick\"; then\n"
    "        return 0\n"
    "    fi\n"
    "    partition=$(blkid -L Ventoy) || fail \"no partition labelled Ventoy\"\n"
    "    if [ ! -e \"/dev/mapper/$view\" ]; then\n"
    "        dmsetup create \"$view\" --readonly --table \"0 $(blockdev --getsz \"$partition\") linear $partition 0\" ||\n"
    "            fail \"could not map $partition read-only\"\n"
    "    fi\n"
    "    mkdir -p \"$stick\"\n"
    "    mount -o ro \"/dev/mapper/$view\" \"$stick\" || fail \"could not mount /dev/mapper/$view on $stick\"\n"
    "    say \"stick: $partition, read-only through /dev/mapper/$view on $stick\"\n"
    "}\n"
    "\n"
    "release_starting_mount() {\n"
    "    source=$(findmnt -n -o SOURCE --target \"$running_from\") || return 0\n"
    "    case \"$source\" in\n"
    "        /dev/loop*)\n"
    "            target=$(findmnt -n -o TARGET --target \"$running_from\")\n"
    "            umount -l \"$target\" || say \"could not release $target, unmount it after the install\"\n"
    "            ;;\n"
    "    esac\n"
    "}\n"
    "\n"
    "[ \"$(id -u)\" -eq 0 ] || fail \"run this as root\"\n"
    "attach_stick\n"
    "bundle=\"$stick/imprint\"\n"
    "[ -f \"$bundle/imprint-engine\" ] && [ -f \"$bundle/$setup.json\" ] ||\n"
    "    fail \"$bundle holds no imprint-engine or $setup.json\"\n"
    "release_starting_mount\n"
    "cd /\n"
    "exec \"$bundle/imprint-engine\" install \"$bundle/$setup.json\" \"$@\"\n";

char *stick_installer_text(const char *setup_name) {
    return text_format(TEMPLATE, setup_name, setup_name);
}
